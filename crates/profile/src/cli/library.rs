//! `profile library new` — scaffold an external preset/recipe library.
//! `profile library normalize` — restyle TOML files in a library.
//!
//! Creates the directory tree and writes a starter README, validate
//! workflow, and a copy of every embedded DDM preset + MDM recipe.
//! End users point contour at the resulting directory via
//! `--preset-path` / `--recipe-path` (or drop into
//! `~/.contour/{presets,recipes}/`).
//!
//! ## Normalize
//!
//! `library normalize <PATH> --style {flat,nested}` rewrites every
//! `.toml` file under `<PATH>/ddm/` and `<PATH>/recipes/` so headers
//! and key/value lines line up with the chosen style. Indentation in
//! TOML is purely cosmetic — semantics are preserved bit-for-bit.
//! Comments and blank lines pass through verbatim.

use crate::ddm::presets;
use crate::output::OutputMode;
use crate::recipe;
use anyhow::{Context, Result};
use colored::Colorize;
use std::path::{Path, PathBuf};

const README_BODY: &str = r"# Contour preset & recipe library

Generated by `contour profile library new`. Drop one TOML file per
intent into `ddm/` (DDM bundles) or `recipes/` (MDM mobileconfig
recipes), then point contour at this directory:

```bash
# DDM
contour profile ddm compose \
    --preset-path ./ddm \
    --preset <name> \
    --org com.acme \
    -o ./out

# MDM
contour profile generate \
    --recipe-path ./recipes \
    --recipe <name> \
    --org com.acme \
    -o ./out
```

## Resolution order

contour looks up names in this order:

1. **Explicit `--preset-path` / `--recipe-path`** (file or directory)
2. **`~/.contour/presets/`** or **`~/.contour/recipes/`**
3. **Embedded built-ins** compiled into the contour binary

External entries win on collision. `--list-presets` and `--list-recipes`
flag shadowed names with `(overrides embedded)` so you can see what is
shadowing what.

## Authoring

Each `.toml` filename (without the extension) is the preset/recipe
name. The first comment block at the top of each file becomes the
listing description, so write a short summary on every file.

Every `.toml` ships with a sibling `<name>.meaning.md` — a markdown
sidecar for the deeper context that does not fit in a TOML header
(intent, platforms, Apple-side defaults, references). Edit the
sidecar when you change the TOML; reviewers read the markdown to
understand *why* a preset exists, not just *what* it sets.

The starter files copied into this library are exact replicas of the
embedded built-ins — modify them in place to override, or rename to
add new intents alongside.

## CI

`.github/workflows/validate.yml` runs `--list-presets` / `--list-recipes`
on every push and smoke-composes each entry with a synthetic `--org`,
catching malformed TOML before it reaches end users.
";

