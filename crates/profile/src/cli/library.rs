/// Options for `library new`.
#[derive(Debug)]
pub struct LibraryNewOptions<'a> {
    pub path: &'a Path,
    pub include_presets: bool,
    pub include_recipes: bool,
    pub force: bool,
}

/// Scaffold a preset/recipe library at `opts.path`. Returns the list of
/// files written so the JSON emitter can advertise them.
pub fn handle_library_new(opts: LibraryNewOptions<'_>, output_mode: OutputMode) -> Result<()> {
    let root = opts.path;

    // Refuse to overwrite a non-empty directory unless --force.
    if root.exists() {
        if !root.is_dir() {
            anyhow::bail!("{} exists and is not a directory", root.display());
        }
        let has_entries = std::fs::read_dir(root)
            .with_context(|| format!("Failed to read {}", root.display()))?
            .next()
            .is_some();
        if has_entries && !opts.force {
            anyhow::bail!(
                "{} already exists and is not empty. Re-run with --force to overwrite.",
                root.display()
            );
        }
    }

    std::fs::create_dir_all(root)
        .with_context(|| format!("Failed to create {}", root.display()))?;

    let mut written: Vec<PathBuf> = Vec::new();

    // Top-level files.
    write_file(
        &root.join("README.md"),
        README_BODY.as_bytes(),
        &mut written,
    )?;
    write_file(
        &root.join(".gitignore"),
        GITIGNORE_BODY.as_bytes(),
        &mut written,
    )?;

    // CI workflow.
    let workflow_dir = root.join(".github/workflows");
    std::fs::create_dir_all(&workflow_dir)
        .with_context(|| format!("Failed to create {}", workflow_dir.display()))?;
    write_file(
        &workflow_dir.join("validate.yml"),
        VALIDATE_WORKFLOW.as_bytes(),
        &mut written,
    )?;

    // DDM presets — each TOML gets a sibling `.meaning.md` describing
    // intent in human-readable markdown.
    if opts.include_presets {
        let ddm_dir = root.join("ddm");
        std::fs::create_dir_all(&ddm_dir)
            .with_context(|| format!("Failed to create {}", ddm_dir.display()))?;
        for (name, desc, body) in presets::EMBEDDED {
            let toml_target = ddm_dir.join(format!("{name}.toml"));
            write_file(&toml_target, body.as_bytes(), &mut written)?;
            let meaning_target = ddm_dir.join(format!("{name}.meaning.md"));
            write_file(
                &meaning_target,
                meaning_md_for(name, desc, body, "DDM bundle").as_bytes(),
                &mut written,
            )?;
        }
    }

    // MDM recipes — schema-enriched sidecar via the import path's
    // generator. Falls back to the simpler `meaning_md_for` if the
    // TOML doesn't parse as a Recipe (defensive — embedded recipes
    // always parse).
    if opts.include_recipes {
        let recipes_dir = root.join("recipes");
        std::fs::create_dir_all(&recipes_dir)
            .with_context(|| format!("Failed to create {}", recipes_dir.display()))?;
        let registry = crate::cli::generate::load_registry(None).ok();
        for (name, body) in recipe::loader::embedded_recipes() {
            let toml_target = recipes_dir.join(format!("{name}.toml"));
            write_file(&toml_target, body.as_bytes(), &mut written)?;
            let meaning_target = recipes_dir.join(format!("{name}.meaning.md"));
            let meaning_body = match toml::from_str::<crate::recipe::Recipe>(body) {
                Ok(parsed) => crate::cli::import_recipe::build_meaning_md(
                    &parsed,
                    &toml_target,
                    registry.as_ref(),
                ),
                Err(_) => meaning_md_for(name, "", body, "MDM recipe"),
            };
            write_file(&meaning_target, meaning_body.as_bytes(), &mut written)?;
        }
    }

    match output_mode {
        OutputMode::Json => emit_json(root, &written)?,
        OutputMode::Human => emit_human(root, &written, &opts),
    }

    Ok(())
}

/// Build the `<name>.meaning.md` sibling for a preset or recipe.
///
/// Pulls the leading TOML comment block as the "Intent" body so the
/// authored context flows naturally into the markdown sidecar. The
/// rest is a fixed template the operator fills in.
fn meaning_md_for(name: &str, fallback_desc: &str, toml_body: &str, kind: &str) -> String {
    let intent = extract_leading_toml_comments(toml_body)
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| {
            if fallback_desc.is_empty() {
                format!("Describe what `{name}` does and why this library ships it.")
            } else {
                fallback_desc.to_string()
            }
        });

    format!(
        "# {name}\n\
        \n\
        {kind} sidecar — fill in the sections below to document what this\n\
        intent does, where it applies, and where the authoritative\n\
        spec lives. The listing description still comes from the\n\
        leading comment block of `{name}.toml`; this file is for the\n\
        deeper context that does not fit in a TOML header.\n\
        \n\
        ## Intent\n\
        \n\
        {intent}\n\
        \n\
        ## Platforms\n\
        \n\
        - [ ] macOS\n\
        - [ ] iOS / iPadOS\n\
        - [ ] tvOS\n\
        - [ ] visionOS\n\
        \n\
        ## Apple defaults\n\
        \n\
        Note any keys whose Apple-side default differs from this preset\n\
        — those are the ones that *actually* change behaviour when this\n\
        intent applies.\n\
        \n\
        ## References\n\
        \n\
        - Apple device-management spec: <https://developer.apple.com/documentation/devicemanagement>\n\
        - contour schema lookup: `contour profile info <payload_type> --full`\n\
        \n\
        ## Compose example\n\
        \n\
        ```bash\n\
        contour profile ddm compose \\\n    --preset-path ./ddm \\\n    --preset {name} \\\n    --org com.acme \\\n    -o ./out\n\
        ```\n",
    )
}

/// Best-effort extraction of the leading `# ...` comment block of a
/// TOML body. Returns the comment lines joined with newlines (`#`
/// stripped, blank lines dropped at the boundary).
fn extract_leading_toml_comments(toml_body: &str) -> Option<String> {
    let mut lines: Vec<String> = Vec::new();
    for line in toml_body.lines() {
        let trimmed = line.trim_start();
        if trimmed.is_empty() {
            if lines.is_empty() {
                continue;
            }
            break;
        }
        if let Some(rest) = trimmed.strip_prefix('#') {
            let cleaned = rest.trim_start_matches([' ', '#']).trim_end();
            lines.push(cleaned.to_string());
        } else {
            break;
        }
    }
    if lines.is_empty() {
        None
    } else {
        Some(lines.join("\n"))
    }
}

fn write_file(path: &Path, body: &[u8], written: &mut Vec<PathBuf>) -> Result<()> {
    std::fs::write(path, body).with_context(|| format!("Failed to write {}", path.display()))?;
    written.push(path.to_path_buf());
    Ok(())
}

fn emit_json(root: &Path, written: &[PathBuf]) -> Result<()> {
    let payload = serde_json::json!({
        "success": true,
        "root": root.display().to_string(),
        "files": written.iter().map(|p| p.display().to_string()).collect::<Vec<_>>(),
        "file_count": written.len(),
    });
    println!("{}", serde_json::to_string_pretty(&payload)?);
    Ok(())
}

fn emit_human(root: &Path, written: &[PathBuf], opts: &LibraryNewOptions<'_>) {
    println!(
        "{} Scaffolded preset library at {}",
        "✓".green(),
        root.display().to_string().bold()
    );
    println!("  {} files written", written.len());
    if opts.include_presets {
        println!(
            "  {} ddm/      ({} embedded preset(s))",
            "•".cyan(),
            presets::EMBEDDED.len()
        );
    }
    if opts.include_recipes {
        println!(
            "  {} recipes/  ({} embedded recipe(s))",
            "•".cyan(),
            recipe::loader::embedded_recipes().len()
        );
    }
    println!();
    println!("Next steps:");
    println!("  cd {}", root.display());
    println!("  contour profile ddm compose --preset-path ./ddm --list-presets");
    println!("  contour profile generate    --recipe-path ./recipes --list-recipes");
}

